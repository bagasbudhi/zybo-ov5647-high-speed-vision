"""Extract the OV5647 common and VGA register data from a pinned Linux driver.

The generated register data is derived from GPL-2.0 Linux source. Keep its
source/license header when redistributing the generated Tcl file.
"""

from pathlib import Path
import re


ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "build" / "ov5647_linux_source.c"
OUTPUT = ROOT / "fpga" / "ov5647_vga_regs.tcl"
COMMIT = "f47d223627f80cb7a1eb14c585fe6cb35de5e984"


def extract(name: str, source: str) -> list[tuple[int, int]]:
    pattern = rf"static const struct reg_sequence {name}\[\] = \{{(.*?)\n\}};"
    match = re.search(pattern, source, flags=re.DOTALL)
    if match is None:
        raise ValueError(f"Missing register array: {name}")
    pairs = [(int(a, 16), int(v, 16)) for a, v in re.findall(
        r"\{\s*0x([0-9a-fA-F]+)\s*,\s*0x([0-9a-fA-F]+)\s*\}", match.group(1)
    )]
    if not pairs:
        raise ValueError(f"Empty register array: {name}")
    return pairs


source = SOURCE.read_text(encoding="utf-8")
common = extract("ov5647_common_regs", source)
vga = extract("ov5647_640x480_10bpp", source)
assert common[:2] == [(0x0100, 0x00), (0x0103, 0x01)]
assert vga[-1] == (0x0100, 0x01)
assert dict(vga)[0x3808] == 0x02 and dict(vga)[0x3809] == 0x80
assert dict(vga)[0x380A] == 0x01 and dict(vga)[0x380B] == 0xE0

lines = [
    "# SPDX-License-Identifier: GPL-2.0-only",
    "# Register data derived from Linux drivers/media/i2c/ov5647.c",
    f"# Source commit: https://github.com/torvalds/linux/blob/{COMMIT}/drivers/media/i2c/ov5647.c",
    "# Generated by fpga/extract_ov5647_vga.py. Do not edit by hand.",
]
for name, pairs in (("ov5647_common_regs", common), ("ov5647_vga_regs", vga)):
    lines.append(f"set {name} {{")
    lines.extend(f"    {{0x{address:04X} 0x{value:02X}}}" for address, value in pairs)
    lines.append("}")

OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"Wrote {OUTPUT}: {len(common)} common + {len(vga)} VGA register writes")
