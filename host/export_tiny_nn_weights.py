"""Export the trained tiny MLP as synthesizable SystemVerilog constant functions."""

import argparse
import math
from pathlib import Path

try:
    from .tiny_nn_detector import HIDDEN, GRID, load_model
except ImportError:
    from tiny_nn_detector import HIDDEN, GRID, load_model


SCALE = 64
SCORE_THRESHOLD_Q12 = round(math.log(0.88 / 0.12) * SCALE * SCALE)


def sv_literal(width: int, value: int) -> str:
    sign = "-" if value < 0 else ""
    return f"{sign}{width}'sd{abs(value)}"


def export(model_path: Path, output: Path) -> None:
    model = load_model(model_path)
    q_w1 = [[round(v * SCALE) for v in row] for row in model.w1]
    q_b1 = [round(v * SCALE) * 255 for v in model.b1]
    q_w2 = [round(v * SCALE) for v in model.w2]
    q_b2 = round(model.b2 * SCALE * SCALE)
    lines = [
        "// Generated by host/export_tiny_nn_weights.py. Do not hand edit.",
        f"localparam signed [31:0] NN_BIAS2_Q12 = {sv_literal(32, q_b2)};",
        f"localparam signed [31:0] NN_SCORE_THRESHOLD_Q12 = {sv_literal(32, SCORE_THRESHOLD_Q12)};",
        "function automatic signed [15:0] nn_weight1(input [2:0] neuron, input [3:0] tap);",
        "  begin",
        "    case ({neuron, tap})",
    ]
    for n in range(HIDDEN):
        for tap in range(GRID * GRID):
            value = q_w1[n][tap]
            lines.append(f"      7'd{n * GRID * GRID + tap}: nn_weight1 = {sv_literal(16, value)};")
    lines += ["      default: nn_weight1 = 16'sd0;", "    endcase", "  end", "endfunction", "",
              "function automatic signed [31:0] nn_bias1(input [2:0] neuron);", "  begin",
              "    case (neuron)"]
    for n, value in enumerate(q_b1):
        lines.append(f"      3'd{n}: nn_bias1 = {sv_literal(32, value)};")
    lines += ["      default: nn_bias1 = 32'sd0;", "    endcase", "  end", "endfunction", "",
              "function automatic signed [15:0] nn_weight2(input [2:0] neuron);", "  begin",
              "    case (neuron)"]
    for n, value in enumerate(q_w2):
        lines.append(f"      3'd{n}: nn_weight2 = {sv_literal(16, value)};")
    lines += ["      default: nn_weight2 = 16'sd0;", "    endcase", "  end", "endfunction", ""]
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines), encoding="ascii", newline="\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model", type=Path, default=Path("models/tiny_patch_detector.json"))
    parser.add_argument("--output", type=Path, default=Path("rtl/tiny_patch_weights.svh"))
    args = parser.parse_args()
    export(args.model, args.output)
    print(f"WEIGHTS={args.output}")
    print(f"SCORE_THRESHOLD_Q12={SCORE_THRESHOLD_Q12}")


if __name__ == "__main__":
    main()
